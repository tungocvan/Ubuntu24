#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

INVENTORY_DIR="${UBUNTU24_INVENTORY_DIR:-/var/local/ubuntu24/inventory}"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
PROJECT_DIR="$(dirname -- "$SCRIPT_DIR")"
OUTPUT_DIR="${UBUNTU24_EXPORT_DIR:-$PROJECT_DIR/exports}"
SNAPSHOT=""
LATEST=false

usage() {
  cat <<'EOF'
Usage: sudo bash scripts/export-os-report.sh [--latest | --snapshot SNAPSHOT_NAME] [--output-dir ABSOLUTE_PATH] [--inventory-dir ABSOLUTE_PATH]
Exports one local OS inventory snapshot into a new .tar.gz archive.
  --latest             Select latest timestamp-named snapshot (default)
  --snapshot NAME      Select a specific snapshot directory by basename
  --inventory-dir DIR  Inventory root (default: /var/local/ubuntu24/inventory)
  --output-dir DIR     Export directory (default: PROJECT_ROOT/exports)
  --help               Show this help
Archives are never overwritten. Requires root. No upload is performed.
EOF
}
log() { printf '[%s] %s\n' "$1" "$2"; }
die() { log ERROR "$1" >&2; exit 1; }
while (($#)); do
  case "$1" in
    --latest) LATEST=true; shift ;;
    --snapshot) (($# >= 2)) || die "Missing snapshot name"; SNAPSHOT="$2"; shift 2 ;;
    --inventory-dir) (($# >= 2)) || die "Missing inventory directory"; INVENTORY_DIR="$2"; shift 2 ;;
    --output-dir) (($# >= 2)) || die "Missing output directory"; OUTPUT_DIR="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) die "Unknown argument: $1" ;;
  esac
done
[[ $EUID -eq 0 ]] || die "Run with sudo/root"
[[ "$INVENTORY_DIR" == /* && "$INVENTORY_DIR" != "/" ]] || die "Inventory directory must be absolute"
[[ -d "$INVENTORY_DIR" && ! -L "$INVENTORY_DIR" ]] || die "Inventory directory missing or symlink"
[[ "$OUTPUT_DIR" == /* && "$OUTPUT_DIR" != "/" && ! -L "$OUTPUT_DIR" ]] || die "Unsafe output directory"
[[ "$INVENTORY_DIR" != "$OUTPUT_DIR" ]] || die "Output directory must differ from inventory directory"
[[ -z "$SNAPSHOT" || "$LATEST" == false ]] || die "Use --latest or --snapshot, not both"
if [[ -z "$SNAPSHOT" ]]; then
  # Names generated by collect-os-config.sh sort chronologically in UTC.
  while IFS= read -r name; do SNAPSHOT="$name"; done < <(
    find "$INVENTORY_DIR" -mindepth 1 -maxdepth 1 -type d \
      -regextype posix-extended \
      -regex '.*/[0-9]{8}T[0-9]{6}Z_[0-9]{3}' \
      -printf '%f\n' | LC_ALL=C sort
  )
fi
[[ -n "$SNAPSHOT" ]] || die "No snapshots found"
[[ "$SNAPSHOT" =~ ^[0-9]{8}T[0-9]{6}Z_[0-9]{3}$ ]] || die "Invalid snapshot name"
SOURCE="$INVENTORY_DIR/$SNAPSHOT"
[[ -d "$SOURCE" && ! -L "$SOURCE" && -f "$SOURCE/manifest.txt" ]] || die "Snapshot missing, unsafe or incomplete"
# Reject symlinks and unexpected file types in the snapshot.
if find "$SOURCE" -mindepth 1 ! -type f -print -quit | grep -q .; then
  die "Snapshot contains symlinks or unsupported entries"
fi
EXPORT_DIR_PREEXISTED=1
if [[ ! -e "$OUTPUT_DIR" && ! -L "$OUTPUT_DIR" ]]; then
  unset EXPORT_DIR_PREEXISTED
  install -d -m 0700 -- "$OUTPUT_DIR"
fi
[[ -d "$OUTPUT_DIR" && ! -L "$OUTPUT_DIR" ]] || die "Unsafe export directory"
EXPORT_UID=0
EXPORT_GID=0
if [[ "$OUTPUT_DIR" == "$PROJECT_DIR/exports" && "${SUDO_UID:-}" =~ ^[0-9]+$ && "${SUDO_GID:-}" =~ ^[0-9]+$ && "${SUDO_UID:-0}" -ne 0 ]]; then
  EXPORT_UID="$SUDO_UID"
  EXPORT_GID="$SUDO_GID"
  # New directory only: make it accessible to the invoking sudo user.
  if [[ -z "${EXPORT_DIR_PREEXISTED:-}" ]]; then
    chown "$EXPORT_UID:$EXPORT_GID" -- "$OUTPUT_DIR"
  fi
fi
DEST=""
for ((i=0; i<1000; i++)); do
  printf -v suffix '%03d' "$i"
  candidate="$OUTPUT_DIR/ubuntu24-inventory_${SNAPSHOT}_${suffix}.tar.gz"
  if (set -C; : > "$candidate") 2>/dev/null; then DEST="$candidate"; break; fi
done
[[ -n "$DEST" ]] || die "Could not allocate a unique archive filename"
if ! tar -C "$INVENTORY_DIR" -czf "$DEST" -- "$SNAPSHOT"; then
  die "Archive creation failed; partial file preserved at: $DEST"
fi
if ! gzip -t "$DEST" || ! tar -tzf "$DEST" >/dev/null; then
  die "Archive validation failed; file preserved for investigation: $DEST"
fi
chmod 0600 -- "$DEST"
chown "$EXPORT_UID:$EXPORT_GID" -- "$DEST"
log SUCCESS "Export completed: $DEST"
log INFO "Snapshot: $SOURCE"
log INFO "Archive size: $(du -h "$DEST" | cut -f1)"
log WARNING "Review hostnames, usernames, IP addresses and service metadata before sharing."
